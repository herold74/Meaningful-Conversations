#!/usr/bin/env python3
"""Prepare cleaned UI PNGs for Figma / manual ASC compositing (v2.6.0)."""

from __future__ import annotations

import importlib.util
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "screenshots/app-store/v2.6.0/_source"
OUT = SRC / "clean"

# Long edge target for Figma (keep aspect; device exports ~1179×2556)
MAX_LONG_EDGE = 2556
SCREEN_SIZE = (1179, 2556)


def fit_cover(im: Image.Image, tw: int, th: int) -> Image.Image:
    sw, sh = im.size
    scale = max(tw / sw, th / sh)
    nw, nh = int(sw * scale), int(sh * scale)
    im = im.resize((nw, nh), Image.Resampling.LANCZOS)
    left, top = (nw - tw) // 2, (nh - th) // 2
    return im.crop((left, top, left + tw, top + th))

MAPPING = {
    "de": [
        ("01-about-coach-knows-you.png", "about-coach-knows-you-de.png"),
        ("02-radar.png", "IMG_1649.PNG"),
        ("03-connector-scenario.png", "IMG_1648.PNG"),
        ("04-practice-about.png", "about-coach-practice-de-light.png"),
        ("05-coach-grid.png", "IMG_1647.PNG"),
    ],
    "en": [
        ("01-about-coach-knows-you.png", "about-coach-knows-you-en.png"),
        ("02-radar.png", "connector-radar-en-light.png"),
        ("03-connector-scenario.png", "connector-catalog-en.png"),
        ("04-practice-about.png", "about-coach-practice-en.png"),
        ("05-coach-grid.png", "coach-grid-connector-en.png"),
    ],
}

_v260 = importlib.util.spec_from_file_location(
    "compose_v260", ROOT / "scripts/compose-asc-marketing-slides-v260.py"
)
_mod = importlib.util.module_from_spec(_v260)
assert _v260.loader
_v260.loader.exec_module(_mod)
clean = _mod.clean_phone_screenshot


def normalize_long_edge(im: Image.Image) -> Image.Image:
    w, h = im.size
    long_edge = max(w, h)
    if long_edge <= MAX_LONG_EDGE:
        return im
    scale = MAX_LONG_EDGE / long_edge
    nw, nh = int(w * scale), int(h * scale)
    return im.resize((nw, nh), Image.Resampling.LANCZOS)


def export_radar_zoom(locale: str, radar_name: str) -> None:
    """Extra crop for Figma floating card on slide 2."""
    path = SRC / radar_name
    if not path.exists():
        return
    im = clean(Image.open(path).convert("RGB"))
    w, h = im.size
    bbox = (int(w * 0.05), int(h * 0.30), int(w * 0.95), int(h * 0.58))
    crop = im.crop(bbox)
    dest = OUT / locale / "02-radar-zoom-chart.png"
    dest.parent.mkdir(parents=True, exist_ok=True)
    crop.save(dest, "PNG", optimize=True)
    print(f"  ✓ {dest.relative_to(ROOT)}")


def main() -> None:
    for locale, files in MAPPING.items():
        dest_dir = OUT / locale
        dest_dir.mkdir(parents=True, exist_ok=True)
        print(f"\n{locale.upper()}:")
        for out_name, src_name in files:
            src_path = SRC / src_name
            if not src_path.exists():
                print(f"  ⚠ missing {src_name}")
                continue
            im = clean(Image.open(src_path).convert("RGB"))
            im = normalize_long_edge(im)
            if out_name != "02-radar-zoom-chart.png":
                im = fit_cover(im, *SCREEN_SIZE)
            dest = dest_dir / out_name
            im.save(dest, "PNG", optimize=True)
            print(f"  ✓ {dest.relative_to(ROOT)} ← {src_name} ({im.size[0]}×{im.size[1]})")
        radar_src = next(s for o, s in files if o.startswith("02-"))
        export_radar_zoom(locale, radar_src)

    readme = OUT / "README.md"
    readme.write_text(
        "# Clean UI for Figma\n\nGenerated by `scripts/export-asc-clean-sources.py`.\n"
        "Do not edit by hand — re-run script after `_source` updates.\n",
        encoding="utf-8",
    )
    print(f"\nDone → {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
